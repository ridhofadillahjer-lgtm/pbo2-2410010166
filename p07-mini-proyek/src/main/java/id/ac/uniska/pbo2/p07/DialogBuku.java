        private void simpan() {
        String kode = kodeField.getText().trim();
        String judul = judulField.getText().trim();
        String penulis = penulisField.getText().trim();
        String tahunTeks = tahunField.getText().trim();

        if (kode.isEmpty()) {
            pesanLabel.setText("Kode wajib diisi");
            kodeField.requestFocusInWindow();
            return;
        }
        if (judul.isEmpty()) {
            pesanLabel.setText("Judul wajib diisi");
            judulField.requestFocusInWindow();
            return;
        }
        int sekarang = Year.now().getValue();
        if (!tahunTeks.matches("\\d{4}")
                || Integer.parseInt(tahunTeks) < 1900
                || Integer.parseInt(tahunTeks) > sekarang) {
            pesanLabel.setText("Tahun terbit berupa angka 1900 sampai " + sekarang);
            tahunField.requestFocusInWindow();
            return;
        }

        Buku buku = new Buku(kode, judul, Integer.parseInt(tahunTeks), penulis);
        if (statusCombo.getSelectedItem() == StatusKoleksi.DIPINJAM) {
            buku.pinjam();
        }
        hasil = buku;
        dispose();
    }

