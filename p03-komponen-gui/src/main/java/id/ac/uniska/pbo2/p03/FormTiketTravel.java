    private void tampilkanPesanan() {
   String kelas = ekonomiRadio.isSelected() ? "Ekonomi"
            : bisnisRadio.isSelected() ? "Bisnis"
            : "Eksekutif";

    List<String> fasilitas = new ArrayList<>();

    for (javax.swing.JCheckBox cb : List.of(
            bagasiCheck,
            makanCheck,
            asuransiCheck)) {

        if (cb.isSelected()) {
            fasilitas.add(cb.getText());
        }
    }

    String pesan = "Nama Pemesan: " + namaField.getText()
            + "\nNomor HP: " + hpField.getText()
            + "\nKota Tujuan: " + tujuanCombo.getSelectedItem()
            + "\nKelas: " + kelas
            + "\nFasilitas Tambahan: "
            + (fasilitas.isEmpty() ? "-" : String.join(", ", fasilitas))
            + "\nCatatan: " + catatanArea.getText();

    javax.swing.JOptionPane.showMessageDialog(
            this,
            pesan,
            "Ringkasan Pemesanan",
            javax.swing.JOptionPane.INFORMATION_MESSAGE
    );
}
    
